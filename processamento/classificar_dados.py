import unicodedata


def _normalizar_para_busca(texto: str) -> str:
    """Converte texto para minúsculas e remove acentos para comparação consistente."""
    if not texto or not isinstance(texto, str):
        return ""
    texto_lower = texto.lower()
    nfkd = unicodedata.normalize("NFKD", texto_lower)
    sem_acento = "".join(c for c in nfkd if not unicodedata.combining(c))
    return re.sub(r"\s+", " ", sem_acento).strip()


def _contem_termo(texto_norm: str, palavras: Set[str], termo: str) -> bool:
    """
    Verifica a presença de um termo no texto normalizado.
    - Para palavras simples (apenas caracteres alfanuméricos), utiliza busca O(1) no conjunto `palavras`.
    - Para termos compostos (com espaços) ou hifenizados/pontuados (ex: 'nf-e', 'go-live', 'pos-venda'),
      utiliza expressão regular com fronteira de palavra para evitar falsos positivos de substring
      e garantir correspondência exata de termos técnicos com hífen.
    """
    if not termo:
        return False
    if " " in termo or "-" in termo or "/" in termo:
        padrao = r"(?<!\w)" + re.escape(termo) + r"(?!\w)"
        return bool(re.search(padrao, texto_norm))
    return termo in palavras


